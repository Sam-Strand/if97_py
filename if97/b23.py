'''
Граница областей 2 и 3, уравнения (5) и (6), коэффициенты — Таблица 1.

Лежит на верхнем уровне рядом с saturation: это линия на диаграмме, а не
область. Зависит только от констант, поэтому её импортируют и границы
областей, и выбор подобласти области 3, без циклов.

Контрольная точка стандарта: T = 623.15 K, p = 16.5291643 МПа.
Действует от 623.15 K при 16.5292 МПа до 863.15 K при 100 МПа.
'''

from math import sqrt

from numba import njit

from ._jit import JIT

N1 = 0.34805185628969e3
N2 = -0.11671859879975e1
N3 = 0.10192970039326e-2
N4 = 0.57254459862746e3
N5 = 0.13918839778870e2


@njit(**JIT)
def p_t(t):
    '''Давление на границе 2/3 по температуре, МПа.'''
    return N1 + N2 * t + N3 * t * t


@njit(**JIT)
def t_p(p):
    '''Температура на границе 2/3 по давлению, K.'''
    return N4 + sqrt((p - N5) / N3)


@njit(**JIT)
def p_t_batch(t, out):
    for k in range(t.shape[0]):
        out[k] = p_t(t[k])


@njit(**JIT)
def t_p_batch(p, out):
    for k in range(p.shape[0]):
        out[k] = t_p(p[k])
