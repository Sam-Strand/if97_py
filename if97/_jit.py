'''
Опции компиляции numba.

Два профиля, и разница между ними принципиальная.

`fastmath=True` ставит в LLVM флаги nnan и ninf — «NaN и бесконечностей не
бывает». Под ними проверка вида `x != x` сворачивается в False, а арифметика
с NaN становится неопределённой. Для функций, которые сами возвращают NaN вне
области определения и проверяют его у соседей, это means испорченный контракт,
поэтому у них fastmath выключен. Стоят они копейки: сравнения и полиномы
третьей степени, выигрывать там нечего.

Горячие полиномы уравнений состояния NaN не видят — их аргументы уже приведены
— и идут с полным fastmath ради FMA и переассоциации сумм.

`error_model='numpy'` в обоих: деление на ноль даёт inf или NaN, как в numpy,
а не ZeroDivisionError. Исключение из середины цикла по двумстам тысячам точек
— не то поведение, которого ждёшь от расчёта свойств.
'''

