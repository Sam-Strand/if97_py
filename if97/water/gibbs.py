'''
Безразмерная энергия Гиббса области 1 и её производные, уравнение (7).

Все шесть производных снимаются за один обход таблицы: произведение
n·(7.1-π)^I·(τ-1.222)^J считается один раз, а производные получаются
домножением на I, J и делением на основания (Таблица 4).

Лестницы степеней вместо возведения в степень
---------------------------------------------
Наивный обход считает `основание ** показатель` на каждый член таблицы, и
numba разворачивает это в бинарное возведение — шесть-одиннадцать умножений
на член. Вместо этого степени обоих оснований строятся один раз на точку
инкрементально (90 умножений), а внутренний цикл превращается в две
загрузки из массива и умножение. На 34 членах это даёт примерно 2.6x.

Буферы под лестницы приходят аргументами: в пакетном режиме они выделяются
один раз на весь массив, а не на каждую точку. `scratch()` их создаёт.
'''

import numpy as np
from numba import njit

from .._jit import JIT
from . import tables
from . import tables
from .tables import NT, PSTAR, TSTAR

IPOW = 33      # степени (7.1-π): 0..32
JOFF = 41      # сдвиг индекса: показатели (τ-1.222) идут от -41
JPOW = 59      # всего степеней (τ-1.222)

#: Таблицы для заморозки в тонких обёртках.
TAB = (tables.I, tables.J, tables.N)

@njit(**JIT)
def scratch():
    '''Буферы под лестницы степеней.'''
    return np.empty(IPOW), np.empty(JPOW)


@njit(**JIT)
def reduce(t, p):
    '''Приведённые переменные: π = p/16.53 МПа, τ = 1386 K/T.'''
    return p / PSTAR, TSTAR / t


@njit(**JIT)
def derivs(pi, tau, pw_i, pw_j, I, J, N):
    '''γ, γ_π, γ_ππ, γ_τ, γ_ττ, γ_πτ.'''
    vi = 7.1 - pi
    vj = tau - 1.222
    pw_i[0] = 1.0
    for m in range(1, 33):
        pw_i[m] = pw_i[m - 1] * vi
    pw_j[41] = 1.0
    for m in range(42, 59):
        pw_j[m] = pw_j[m - 1] * vj
    inv = 1.0 / vj
    for m in range(40, -1, -1):
        pw_j[m] = pw_j[m + 1] * inv

    g = 0.0
    si = 0.0
    sii = 0.0
    sij = 0.0
    sj = 0.0
    sjj = 0.0
    for k in range(NT):
        ik = I[k]
        jk = J[k]
        item = N[k] * pw_i[ik] * pw_j[jk + 41]
        i_item = ik * item
        j_item = jk * item
        g += item
        si += i_item
        sii += (ik - 1) * i_item
        sij += jk * i_item
        sj += j_item
        sjj += (jk - 1) * j_item
    # знак минус у производных по π: основание (7.1 - π) убывает с π
    return (g, -si / vi, sii / (vi * vi), sj / vj,
            sjj / (vj * vj), -sij / (vi * vj))
