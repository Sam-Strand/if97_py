'''
Линия B2bc: граница подобластей 2b и 2c, уравнения (20) и (21), Таблица 19.

Это квадратичная подгонка изоэнтропы s = 5.85 кДж/(кг·K), и подгонка грубая:
вдоль линии энтропия гуляет между 5.81 и 5.85. Для выбора подобласти этого
достаточно — по обе стороны границы считают разные уравнения одного и того
же стандарта, и у них общая точка.

Линия идёт от состояния насыщения при 6.546 70 МПа (T = 554.485 K) до
100 МПа (T = 1019.32 K). Ниже PMIN подобласти 2c не существует, и уравнение
(21) там даёт корень из отрицательного числа — спрашивать границу незачем.

Соотношения стандарта: π = n1 + n2 η + n3 η²
                       η = n4 + ((π − n5)/n3)^(1/2)
'''

import numpy as np
from numba import njit

from ._dispatch import make1
from ._jit import JIT, JIT_NAN
from .consts import p2bcMin

#: Таблица 19.
N1 = 0.90584278514723e3
N2 = -0.67955786399241
N3 = 0.12809002730136e-3
N4 = 0.26526571908428e4
N5 = 0.45257578905948e1

#: Давление, на котором линия упирается в кривую насыщения, [МПа].
PMIN = p2bcMin


# Ниже PMIN под корнем отрицательное число. np.sqrt отдаёт там NaN, а не
# комплексное число и не исключение, и fastmath выключен, чтобы этот NaN
# дошёл до вызывающего, а не превратился в неопределённость.
@njit(**JIT_NAN)
def h_p_kernel(p):
    '''Энтальпия на границе по давлению, уравнение (21), [кДж/кг].'''
    return N4 + np.sqrt((p - N5) / N3)


@njit(**JIT_NAN)
def h_p_batch(p, out):
    for k in range(p.shape[0]):
        out[k] = h_p_kernel(p[k])


@njit(**JIT)
def p_h_kernel(h):
    '''Давление на границе по энтальпии, уравнение (20), [МПа].'''
    return N1 + h * (N2 + h * N3)


@njit(**JIT)
def p_h_batch(h, out):
    for k in range(h.shape[0]):
        out[k] = p_h_kernel(h[k])


h_p = make1(h_p_kernel, h_p_batch)
p_h = make1(p_h_kernel, p_h_batch)
